import type { BotContext } from "../context";

/**
 * Fallback-обработчик для сообщений, которые не подошли ни под одну команду
 * и не были пойманы сценарным обработчиком текста (bot/handlers/booking.ts).
 *
 * Поведение зависит от текущего шага диалога:
 *   - в сценарии записи (idle → шаги выбора) — подсказываем продолжить;
 *   - вне сценария — предлагаем /start.
 */
export async function handleFallback(ctx: BotContext): Promise<void> {
  const step = ctx.session.step;

  // Внутри активного диалога, но без ожидаемого ввода
  if (step !== "idle") {
    await ctx.reply(
      [
        "Я не понял сообщение.",
        "",
        "Используйте кнопки выше или:",
        "/cancel — сбросить диалог",
        "/start — начать заново",
      ].join("\n"),
    );
    return;
  }

  // Вне диалога
  await ctx.reply(
    [
      "Не понял команду.",
      "",
      "/start — записаться в барбершоп «Барбершопик»",
      "/my — мои записи",
      "/help — список команд",
    ].join("\n"),
  );
}